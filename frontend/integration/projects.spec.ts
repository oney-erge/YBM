import { expect, test } from "@playwright/test"
import path from "node:path"
import { mkdir, writeFile } from "node:fs/promises"

// No HTTP interception: compiled UI -> real FastAPI -> SQLite -> worker ->
// real document adapter -> on-disk artifacts. Only the model is scripted.
test("project editing, approval, artifact download, workflow schedule and controls", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto("./projects?token=ybm-isolated-browser-test")
  await page.getByLabel("Project name", { exact: true }).fill("Vendor review")
  await page.getByLabel("Instructions and corrections").fill("Keep literal evidence.")
  await page.getByLabel("Success criteria").fill("cost\ntimeline")
  await page.getByRole("button", { name: "Create project" }).click()
  await page.getByRole("button", { name: "Edit Vendor review" }).click()
  await page.getByLabel("Instructions and corrections").fill("Include missing evidence explicitly.")
  await page.getByRole("button", { name: "Save changes" }).click()
  await expect(page.getByText("Include missing evidence explicitly.", { exact: true })).toBeVisible()
  await page.getByRole("link", { name: "Open project chat and history" }).click()
  await expect(page.getByRole("combobox", { name: "Project context" })).not.toHaveValue("")
  const sent = page.waitForResponse((response) => response.url().endsWith("/api/chat/messages") && response.request().method() === "POST")
  await page.getByRole("textbox", { name: "Message YBM" }).fill("Compare the two proposals by cost and timeline")
  await page.getByRole("textbox", { name: "Message YBM" }).press("Enter")
  const task = (await (await sent).json()).task
  expect(task.metadata.project_context.instructions).toBe("Include missing evidence explicitly.")
  await page.getByPlaceholder("Type your answer...").fill("Use cost and timeline")
  const replied = page.waitForResponse((response) => response.url().endsWith("/api/chat/messages") && response.request().method() === "POST")
  await page.getByRole("button", { name: "Reply", exact: true }).click()
  const reply = await replied
  expect(reply.request().postDataJSON().project_id).toBe(task.metadata.project_id)
  expect((await reply.json()).task.id).toBe(task.id)
  await page.getByRole("button", { name: "Approve once", exact: true }).click()
  await expect(page.getByText("comparison.xlsx", { exact: true })).toBeVisible()
  const downloaded = page.waitForEvent("download")
  await page.getByText("comparison.xlsx", { exact: true }).locator("..").getByRole("button", { name: "Download", exact: true }).click()
  const download = await downloaded
  expect(await download.failure()).toBeNull()
  expect(download.suggestedFilename()).toMatch(/comparison\.(xlsx|md)$/)
  await page.reload()
  await expect(page.getByText("comparison.xlsx", { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: "test-results/project-chat-mobile.png", fullPage: true })
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto(`./tasks/${task.id}`)
  const trace = await (await page.request.get(`/admin/api/tasks/${task.id}/trace`)).json()
  const sourcePath: string = trace.operator_history.find((step: { tool_name: string }) => step.tool_name === "document.manage").input.source_paths[0]
  expect(sourcePath).toContain("ybm-project-e2e-")
  const inbox = path.join(path.dirname(sourcePath), "inbox")
  await mkdir(inbox)
  await writeFile(path.join(inbox, "baseline.txt"), "Cost: 100 USD.")
  await page.getByRole("button", { name: "Save as workflow", exact: true }).click()
  const save = page.getByRole("dialog")
  await save.getByLabel("Name", { exact: true }).fill("Proposal comparison")
  await save.getByRole("textbox", { name: "Value 1 to parameterize", exact: true }).fill(sourcePath)
  await save.getByRole("textbox", { name: "Parameter 1 name", exact: true }).fill("input_file")
  await save.getByRole("button", { name: "Save workflow", exact: true }).click()
  await page.getByRole("button", { name: "Automate", exact: true }).click()
  const automate = page.getByRole("dialog")
  await automate.getByLabel("Cadence", { exact: true }).fill("tomorrow morning")
  await automate.getByLabel("{{input_file}}", { exact: true }).fill(sourcePath)
  await automate.getByRole("button", { name: "Schedule", exact: true }).click()
  await expect(page.getByText(/Use daily, weekly, or every N/)).toBeVisible()
  await automate.getByLabel("Cadence", { exact: true }).fill("every 2 hours")
  await automate.getByLabel("Timezone", { exact: true }).fill("UTC")
  await automate.getByLabel("Project", { exact: true }).selectOption({ label: "Vendor review" })
  await automate.getByRole("button", { name: "Schedule", exact: true }).click()
  await expect(page.getByText("enabled - every 2 hours - UTC", { exact: true })).toBeVisible()
  await page.screenshot({ path: "test-results/project-automation.png", fullPage: true })
  await page.getByRole("button", { name: "Pause", exact: true }).click()
  await expect(page.getByText("paused - every 2 hours - UTC", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Resume", exact: true }).click()
  await expect(page.getByText("enabled - every 2 hours - UTC", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Delete automation", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Delete", exact: true }).click()
  await expect(page.getByText("enabled - every 2 hours - UTC", { exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "Automate", exact: true }).click()
  const watching = page.getByRole("dialog")
  await watching.getByLabel("Trigger", { exact: true }).selectOption("folder")
  await watching.getByRole("textbox", { name: "Watch folder", exact: true }).fill(inbox)
  await watching.getByLabel("File extensions", { exact: true }).fill(".txt")
  await watching.getByLabel("Wait for stable file (seconds)", { exact: true }).fill("1")
  await watching.getByLabel("Project", { exact: true }).selectOption({ label: "Vendor review" })
  await watching.getByRole("button", { name: "Watch folder", exact: true }).click()
  await expect(page.getByText("enabled - file changes", { exact: true })).toBeVisible()
  const incoming = path.join(inbox, "incoming.txt")
  await writeFile(incoming, "Cost: 44 USD. Timeline: three weeks.")
  await expect(page.getByRole("link", { name: "Last run and receipt" })).toBeVisible()
  await page.goto(`./?project=${task.metadata.project_id}`)
  await expect(page.getByText(`Started by a file change: ${incoming}`, { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Approve once", exact: true }).click()
  await expect(page.getByText(/^comparison_\d+\.xlsx$/)).toBeVisible()
  await page.screenshot({ path: "test-results/folder-trigger-result.png", fullPage: true })
  await page.goto("./workflows")
  await page.getByRole("button", { name: "Pause", exact: true }).click()
  await expect(page.getByText("paused - file changes", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Resume", exact: true }).click()
  await expect(page.getByText("enabled - file changes", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Delete automation", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Delete", exact: true }).click()
  await expect(page.getByText("enabled - file changes", { exact: true })).toHaveCount(0)
  await page.goto("./projects")
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole("button", { name: "Edit Vendor review" })).toBeVisible()
  await page.screenshot({ path: "test-results/projects-mobile.png", fullPage: true })
  expect(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole("button", { name: "Delete Vendor review", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Delete", exact: true }).click()
  await expect(page.getByText("No projects yet.", { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
